# presets.py
from collections import OrderedDict

# 常用尺寸比例（按比例优先排序）
PRESETS = [
    # 关闭选项
    ("关闭", (0, 0)),
    # 1:1 比例
    ("512×512 (1:1)", (512, 512)),
    ("768×768 (1:1)", (768, 768)),
    ("1024×1024 (1:1)", (1024, 1024)),
    ("1600×1600 (1:1)", (1600, 1600)),
    # 3:2 比例
    ("1536×1024 (3:2)", (1536, 1024)),
    # 2:3 比例
    ("1024×1536 (2:3)", (1024, 1536)),
    # 9:16 比例
    ("720×1280 (9:16)", (720, 1280)),
    ("1080×1920 (9:16)", (1080, 1920)),
    # 16:9 比例
    ("1280×720 (16:9)", (1280, 720)),
    ("1920×1080 (16:9)", (1920, 1080)),
    ("2560×1440 (16:9)", (2560, 1440)),
]

CROP_METHODS = ["中心裁剪", "等比缩放"]
RESIZE_ALGOS = ["lanczos", "bilinear", "nearest"]

def get_size_from_preset(ratio_name):
    """从预设中获取尺寸"""
    for name, wh in PRESETS:
        if name == ratio_name:
            return wh
    return (1024, 1024)  # 默认尺寸