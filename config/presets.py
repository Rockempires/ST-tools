# presets.py

# 预设尺寸（全部为横向基准，宽高均为 16 的倍数，兼容 8/16 倍 VAE）
# 竖版由尺寸节点的"画面方向=竖向"交换宽高得到，不在此重复列出
PRESETS = [
    ("关闭", (0, 0)),
    # 1:1
    ("1024×1024 (1:1 标准)", (1024, 1024)),
    ("1328×1328 (1:1 高清)", (1328, 1328)),
    ("2048×2048 (1:1 超清)", (2048, 2048)),
    # 3:2
    ("1536×1024 (3:2 标准)", (1536, 1024)),
    ("1920×1280 (3:2 高清)", (1920, 1280)),
    ("2400×1600 (3:2 超清)", (2400, 1600)),
    # 4:3
    ("1024×768 (4:3 标准)", (1024, 768)),
    ("1472×1104 (4:3 高清)", (1472, 1104)),
    ("1920×1440 (4:3 2K)", (1920, 1440)),
    ("2304×1728 (4:3 超清)", (2304, 1728)),
    # 16:9
    ("1024×576 (16:9 草稿)", (1024, 576)),
    ("1344×768 (16:9 标准)", (1344, 768)),
    ("1664×928 (16:9 高清)", (1664, 928)),
    ("1920×1088 (16:9 2K)", (1920, 1088)),
    ("2560×1440 (16:9 超清)", (2560, 1440)),
    # 21:9 电影宽屏
    ("1536×640 (21:9 标准)", (1536, 640)),
    ("2304×976 (21:9 高清)", (2304, 976)),
    ("2560×1088 (21:9 超清)", (2560, 1088)),
]

CROP_METHODS = ["中心裁剪", "等比缩放"]
RESIZE_ALGOS = ["lanczos", "bilinear", "nearest"]


def get_size_from_preset(ratio_name, orientation="横向"):
    """返回预设 (宽, 高)；画面方向为竖向时交换宽高，1:1 不受影响。"""
    for name, (w, h) in PRESETS:
        if name == ratio_name:
            if orientation == "竖向" and w != h:
                return h, w
            return w, h
    return 1024, 1024  # 默认尺寸
